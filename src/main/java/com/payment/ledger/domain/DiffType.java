package com.payment.ledger.domain;

/**
 * 对账差异类型。
 *
 * <p><b>差异定性是对账最需要动脑子的一步。</b>「两边不一样」只是现象，
 * 真正决定后续动作的是「哪一侧多、多在什么维度」：
 *
 * <pre>
 *   渠道多我方少  → 钱进了银行，我方没记账  → 用户投诉、平台占了用户的钱
 *   我方多渠道少  → 我方记了账，钱没进来    → 平台资损（钱可能已经被提走）
 *   金额不符      → 一定有一侧算错了        → 停止后续结算，人工介入
 *   手续费不符    → 资金没错，成本/利润错了 → 不影响资金安全，但影响财报
 * </pre>
 *
 * <p>方向搞反了，补救动作就会把窟窿越补越大。
 */
public enum DiffType {

    /** 平账：两侧金额、手续费、状态全部一致 */
    MATCHED,

    /**
     * 在途：我方还在处理中（凭证 PROCESSING），尚未到达终态。
     * <p><b>在途不是差异。</b>把在途当差异报出来，是对账告警最常见的噪音来源——
     * 值班的人被淹没在几千条"差异"里，真正的问题反而看不见了。
     */
    IN_TRANSIT,

    /**
     * 我方单边账：我方有记录，渠道对账单里没有。
     * <p>典型成因：支付超时后我方误判成功、或渠道交易实际失败但我方没收到通知。
     * <p><b>危险方向：平台资损。</b>我方已经给用户加了钱，但这笔钱根本没到账。
     */
    OUR_MORE,

    /**
     * 渠道单边账：渠道对账单里有，我方没有记录。
     * <p>典型成因：回调丢失、我方记账服务宕机、消息队列积压。
     * <p><b>危险方向：用户资损 / 投诉。</b>用户的钱被扣了，账上却没有。
     * 这一类通常可以自动补记账修复——因为「钱确实到了」这个事实是确定的。
     */
    CHANNEL_MORE,

    /**
     * 金额不符：两侧都有记录，但交易金额不一致。
     * <p>最严重的一类。金额对不上意味着某一侧的计算逻辑有 bug，
     * 而 bug 通常不止影响这一笔。<b>必须人工介入，不允许自动修复。</b>
     */
    AMOUNT_MISMATCH,

    /**
     * 手续费不符：金额一致，但渠道收取的通道费与我方账上的成本对不上。
     * <p>不影响资金安全（用户和商户的钱都对），但影响成本核算——
     * 漏记通道成本会让利润虚高，是财务报表失真的常见来源。
     */
    FEE_MISMATCH,

    /**
     * 状态不符：两侧都有记录，但一方成功、一方失败。
     * <p>比金额不符更优先处理：金额不符至少双方都认为交易发生了，
     * 状态不符则是双方对「这笔交易到底成没成」都没达成一致。
     */
    STATUS_MISMATCH;

    /**
     * 是否需要落入差异表并推动处理。
     * <p>{@link #MATCHED} 和 {@link #IN_TRANSIT} 不需要——
     * 对平的不留痕，在途的等下一批。
     */
    public boolean needsHandling() {
        return this != MATCHED && this != IN_TRANSIT;
    }
}
